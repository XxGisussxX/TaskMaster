/**
 * Genera los módulos de datos del motor de documentos:
 *   src/fonts/*.data.ts          -> fuentes TTF/OTF en base64 (data URLs para react-pdf)
 *   src/text/supported.data.ts   -> rangos de code points con cobertura completa
 *
 * Sin dependencias externas: parsea la tabla cmap (format 4 y 12) a mano.
 * Un code point se considera soportado si LO cubren los 4 estilos de AL MENOS
 * una familia (para que regular/bold/italic/bolditalic resuelvan igual).
 *
 * Uso: node scripts/generate-fonts.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fontsDir = join(root, "fonts");

const FAMILIES = [
  {
    constName: "INTER",
    outFile: "src/fonts/inter.data.ts",
    files: {
      regular: "Inter-Regular.otf",
      bold: "Inter-Bold.otf",
      italic: "Inter-Italic.otf",
      boldItalic: "Inter-BoldItalic.otf",
    },
  },
  {
    constName: "SOURCE_SERIF",
    outFile: "src/fonts/source-serif.data.ts",
    files: {
      regular: "SourceSerif4-Regular.ttf",
      bold: "SourceSerif4-Bold.ttf",
      italic: "SourceSerif4-It.ttf",
      boldItalic: "SourceSerif4-BoldIt.ttf",
    },
  },
  {
    constName: "JETBRAINS_MONO",
    outFile: "src/fonts/jetbrains-mono.data.ts",
    files: {
      regular: "JetBrainsMono-Regular.ttf",
      bold: "JetBrainsMono-Bold.ttf",
      italic: "JetBrainsMono-Italic.ttf",
      boldItalic: "JetBrainsMono-BoldItalic.ttf",
    },
  },
];

function readFormat4(buf, off, out) {
  const segCount = buf.readUInt16BE(off + 6) / 2;
  const endBase = off + 14;
  const startBase = endBase + segCount * 2 + 2;
  const deltaBase = startBase + segCount * 2;
  const rangeBase = deltaBase + segCount * 2;
  for (let i = 0; i < segCount; i++) {
    const start = buf.readUInt16BE(startBase + i * 2);
    const end = buf.readUInt16BE(endBase + i * 2);
    if (start === 0xffff || start > end) continue;
    const delta = buf.readInt16BE(deltaBase + i * 2);
    const rangeOffset = buf.readUInt16BE(rangeBase + i * 2);
    const last = Math.min(end, 0xfffe);
    for (let cp = start; cp <= last; cp++) {
      let gid;
      if (rangeOffset === 0) {
        gid = (cp + delta) & 0xffff;
      } else {
        const idx = rangeBase + i * 2 + rangeOffset + (cp - start) * 2;
        if (idx + 1 >= buf.length) continue;
        gid = buf.readUInt16BE(idx);
        if (gid !== 0) gid = (gid + delta) & 0xffff;
      }
      if (gid !== 0) out.add(cp);
    }
  }
}

function readFormat12(buf, off, out) {
  const nGroups = buf.readUInt32BE(off + 12);
  for (let i = 0; i < nGroups; i++) {
    const g = off + 16 + i * 12;
    const start = buf.readUInt32BE(g);
    const end = buf.readUInt32BE(g + 4);
    const gid0 = buf.readUInt32BE(g + 8);
    const last = Math.min(end, 0x10ffff);
    for (let cp = start; cp <= last; cp++) {
      if (gid0 + (cp - start) !== 0) out.add(cp);
    }
  }
}

function cmapCodePoints(buf) {
  const numTables = buf.readUInt16BE(4);
  let cmapOff = -1;
  for (let i = 0; i < numTables; i++) {
    const rec = 12 + i * 16;
    if (buf.toString("ascii", rec, rec + 4) === "cmap") {
      cmapOff = buf.readUInt32BE(rec + 8);
    }
  }
  if (cmapOff < 0) throw new Error("cmap: tabla cmap no encontrada");

  const out = new Set();
  const subtables = buf.readUInt16BE(cmapOff + 2);
  for (let i = 0; i < subtables; i++) {
    const rec = cmapOff + 4 + i * 8;
    const platform = buf.readUInt16BE(rec);
    const encoding = buf.readUInt16BE(rec + 2);
    const use =
      (platform === 3 && (encoding === 1 || encoding === 10)) || platform === 0;
    if (!use) continue;
    const off = cmapOff + buf.readUInt32BE(rec + 4);
    const format = buf.readUInt16BE(off);
    if (format === 4) readFormat4(buf, off, out);
    else if (format === 12) readFormat12(buf, off, out);
  }
  if (out.size === 0) throw new Error("cmap: sin subtablas 4/12 usables");
  return out;
}

function intersect(a, b) {
  const out = new Set();
  for (const cp of a) if (b.has(cp)) out.add(cp);
  return out;
}

function toRanges(codePoints) {
  const sorted = [...codePoints].sort((x, y) => x - y);
  const ranges = [];
  for (const cp of sorted) {
    const last = ranges[ranges.length - 1];
    if (last && cp === last[1] + 1) last[1] = cp;
    else ranges.push([cp, cp]);
  }
  return ranges;
}

const HEADER = "// Generated by scripts/generate-fonts.mjs — DO NOT EDIT.\n";

const supported = new Set();

for (const family of FAMILIES) {
  const styleSets = [];
  const entries = [];
  for (const [style, fileName] of Object.entries(family.files)) {
    const buf = readFileSync(join(fontsDir, fileName));
    styleSets.push(cmapCodePoints(buf));
    entries.push(
      `  ${style}: "${readFileSync(join(fontsDir, fileName)).toString("base64")}",`,
    );
  }
  const coveredByFamily = styleSets.reduce((acc, set) => intersect(acc, set));
  for (const cp of coveredByFamily) supported.add(cp);
  const outFile = join(root, family.outFile);
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(
    outFile,
    `${HEADER}export const ${family.constName} = {\n${entries.join("\n")}\n};\n`,
    "utf8",
  );
  console.log(`${family.outFile}: ${entries.length} estilos`);
}

for (const [cp, name] of [
  [0x41, "A"],
  [0xf1, "ñ"],
  [0x20, "espacio"],
]) {
  if (!supported.has(cp)) throw new Error(`sanity: falta ${name} (U+${cp.toString(16)})`);
}
if (supported.has(0x1f680)) throw new Error("sanity: 🚀 no debería estar soportado");

const ranges = toRanges(supported);
const lines = ranges.map(([a, b]) => `  [0x${a.toString(16).padStart(4, "0")}, 0x${b.toString(16).padStart(4, "0")}],`);
const dataFile = join(root, "src/text/supported.data.ts");
mkdirSync(dirname(dataFile), { recursive: true });
writeFileSync(
  dataFile,
  `${HEADER}export const SUPPORTED_CODEPOINTS: ReadonlyArray<readonly [number, number]> = [\n${lines.join("\n")}\n];\n`,
  "utf8",
);
console.log(`src/text/supported.data.ts: ${ranges.length} rangos, ${supported.size} code points`);
